<?php

declare(strict_types=1);

namespace PhpBaremetal\Conductor;

use PhpBaremetal\Spec\Manifest\Manifest;
use PhpBaremetal\Spec\Manifest\ManifestValidator;

/**
 * Rebuilds vendor/php-baremetal/ide-stubs/: the PHP declarations of the installed packages, for IDEs.
 */
final class IdeStubs
{
    public const DIR = 'vendor/php-baremetal/ide-stubs';

    private int $written = 0;

    private const README = "Generated by php-baremetal/conductor at every composer install/update: the PHP declarations of the installed php-baremetal packages, for IDEs. Do not edit; do not load at runtime.\n";

    /**
     * Rebuilds DIR under $projectDir from the packages of $manifest.
     *
     * @return list<string> warnings (declared stubs that are missing)
     */
    public function write(string $projectDir, Manifest $manifest): array
    {
        $out = $projectDir . '/' . self::DIR;
        $this->written = 0;
        $this->clear($out);
        if (!is_dir($out) && !@mkdir($out, 0777, true) && !is_dir($out)) {
            return ['php-baremetal: cannot create ' . self::DIR];
        }
        if (@file_put_contents($out . '/README.md', self::README) === false) {
            return ['php-baremetal: cannot write ' . self::DIR . '/README.md'];
        }

        $warnings = [];
        $this->written = 0;
        foreach ($manifest->packages as $package) {
            $stubs = $package->meta['ide-stubs'] ?? [];
            if (!is_array($stubs)) {
                continue;
            }
            $base = $this->fileName($package->name);
            $n = 0;
            foreach ($stubs as $stub) {
                if (!is_string($stub)) {
                    continue;
                }
                if (!ManifestValidator::isRelativeStubPath($stub)) {
                    $warnings[] = "php-baremetal: {$package->name}: ide stub '{$stub}' is not a relative .stub path, skipped";
                    continue;
                }
                $source = $this->resolve($projectDir, $package->path) . '/' . $stub;
                if (!is_file($source)) {
                    $warnings[] = "php-baremetal: {$package->name}: ide stub '{$stub}' not found";
                    continue;
                }
                $n++;
                $target = $base . ($n === 1 ? '' : ".{$n}") . '.php';
                if (!@copy($source, $out . '/' . $target)) {
                    $warnings[] = "php-baremetal: {$package->name}: cannot write " . self::DIR . "/{$target}";
                    $n--;
                    continue;
                }
                $this->written++;
            }
        }

        return $warnings;
    }

    /** Number of stub files (README excluded) written by the last write(). */
    public function written(): int
    {
        return $this->written;
    }

    private function fileName(string $name): string
    {
        return str_starts_with($name, 'php-baremetal/') ? substr($name, strlen('php-baremetal/')) : str_replace('/', '--', $name);
    }

    private function resolve(string $projectDir, string $path): string
    {
        $absolute = str_starts_with($path, '/') || preg_match('~^[A-Za-z]:[\\\\/]~', $path) === 1;

        return rtrim($absolute ? $path : $projectDir . '/' . $path, '/\\');
    }

    /** Removes only the *.php files and README.md of $dir, then the folder when it is empty. */
    private function clear(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach (@scandir($dir) ?: [] as $entry) {
            if ((str_ends_with($entry, '.php') || $entry === 'README.md') && is_file($dir . '/' . $entry)) {
                @unlink($dir . '/' . $entry);
            }
        }
        @rmdir($dir);
    }
}
